def generar_fondo_carga(salida):
    """Embed platforms/switch/fondo_carga.jpg in the NRO as 960x540 RGB loading-screen data."""
    from PIL import Image
    origen = RAIZ / "platforms/switch/fondo_carga.jpg"
    destino = salida / "fondo_carga.cpp"
    ancho, alto = 960, 540
    datos = Image.open(origen).convert("RGB").resize((ancho, alto), Image.LANCZOS).tobytes()
    lineas = [f"// Generated by tools/build_switch_direct.py from {origen.name}. Do not edit.",
              f"extern const unsigned lmnx_fondo_carga_ancho = {ancho}, lmnx_fondo_carga_alto = {alto};",
              "extern const unsigned char lmnx_fondo_carga[] ="]
    for k in range(0, len(datos), 4096):
        lineas.append('    "' + "".join("\\%03o" % b for b in datos[k:k + 4096]) + '"')
    lineas[-1] += ";"
    texto = "\n".join(lineas) + "\n"
    if not destino.is_file() or destino.read_text(encoding="ascii") != texto:
        destino.write_text(texto, encoding="ascii")
    return destino

def generar_tabla_vi(salida, dkp):
    """Convert platforms/switch/vi_curva.dat for vi_ajuste.cpp into consecutive 1280x720 8-bit planes compressed as one zstd block. Include the source fingerprint in generated C++."""
    origen = RAIZ / "platforms/switch/vi_curva.dat"
    if not origen.is_file():
        raise SystemExit(f"Missing {origen}: the NRO cannot be built without this data.")
    ancho, alto = 1280, 720
    huella = hashlib.sha256(origen.read_bytes()).hexdigest()[:16]
    datos = salida / f"vi-{huella}.bin"
    crudo = salida / f"vi-{huella}.raw"
    if not datos.is_file():
        ffmpeg = os.environ.get("FFMPEG", shutil.which("ffmpeg") or "ffmpeg")
        subprocess.run([ffmpeg, "-v", "error", "-y", "-i", str(origen), "-vf",
                        f"scale={ancho}:{alto}:flags=lanczos,format=gray", "-f", "rawvideo", str(crudo)], check=True)
        subprocess.run([str(dkp / "msys2/usr/bin/zstd.exe"), "-19", "-q", "-f", str(crudo), "-o", str(datos)], check=True)
    if not crudo.is_file():
        subprocess.run([str(dkp / "msys2/usr/bin/zstd.exe"), "-d", "-q", "-f", str(datos), "-o", str(crudo)], check=True)
    plano = ancho * alto
    planos = crudo.stat().st_size // plano
    from vi_suma import xxh64_por_bloques  # XXH64 seed zero, matching the game.
    clave = xxh64_por_bloques(crudo, plano)
    crudo.unlink(missing_ok=True)
    destino = salida / "vi_tabla.cpp"
    texto = (f"// Generated by tools/build_switch_direct.py (fingerprint {huella}). Do not edit.\n"
             'extern "C" {\n'
             f"extern const unsigned lmnx_vi_w = {ancho}, lmnx_vi_h = {alto}, lmnx_vi_n = {planos}, lmnx_vi_hz = 60;\n"
             f"extern const unsigned long lmnx_vi_tam = {datos.stat().st_size};\n"
             f"extern const unsigned long long lmnx_vi_esperada = 0x{clave:016X}ULL;\n"
             "}\n"
             'asm(".section .rodata.lmnx_vi,\\"a\\",%progbits\\n.balign 16\\n.global lmnx_vi_tabla\\n'
             '.type lmnx_vi_tabla, %object\\nlmnx_vi_tabla:\\n'
             f'.incbin \\"{datos.as_posix()}\\"\\n'
             '.size lmnx_vi_tabla, .-lmnx_vi_tabla\\n.previous\\n");\n')
    if not destino.is_file() or destino.read_text(encoding="ascii") != texto:
        destino.write_text(texto, encoding="ascii")
    return destino

def generar_fuente_aviso(salida):
    """Embed platforms/switch/fuentes/Delfino.ttf in the NRO for src/recomp/ui_scale.cpp. Include the file fingerprint in generated C++."""
    origen = RAIZ / "platforms/switch/fuentes/Delfino.ttf"
    huella = hashlib.sha256(origen.read_bytes()).hexdigest()[:16]
    destino = salida / "fuente_aviso.cpp"
    texto = (f"// Generated by tools/build_switch_direct.py (fingerprint {huella}). Do not edit.\n"
             'extern "C" {\n'
             f"extern const unsigned long lmnx_fuente_aviso_tam = {origen.stat().st_size};\n"
             "}\n"
             'asm(".section .rodata.lmnx_fuente_aviso,\\"a\\",%progbits\\n.balign 16\\n.global lmnx_fuente_aviso\\n'
             '.type lmnx_fuente_aviso, %object\\nlmnx_fuente_aviso:\\n'
             f'.incbin \\"{origen.as_posix()}\\"\\n'
             '.size lmnx_fuente_aviso, .-lmnx_fuente_aviso\\n.previous\\n");\n')
    if not destino.is_file() or destino.read_text(encoding="ascii") != texto:
        destino.write_text(texto, encoding="ascii")
    return destino

