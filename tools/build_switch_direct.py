        core = ["lib/aurora.cpp", "lib/window.cpp", "lib/device.cpp", "lib/gamepad.cpp", "lib/time.cpp", "lib/system_info.cpp",
            "lib/input/binding.cpp", "lib/input/capture.cpp", "lib/input/router.cpp", "lib/input/sdl_input.cpp", "lib/input/source_state.cpp",
            "lib/dolphin/pad/pad.cpp", "lib/dolphin/pad/adapter.cpp", "lib/dolphin/si/si.cpp", "lib/dolphin/vi/vi.cpp", "lib/nativegpu/gpu.cpp", "lib/nativegpu/postfx.cpp", "lib/imgui.cpp"]
        grupos["lmnx_aurora_core"] = ([aurora / f for f in core] + [RAIZ / "platforms/switch/imgui_lmnx.cpp", RAIZ / "platforms/switch/imgui_input_lmnx.cpp", RAIZ / "platforms/switch/vi_ajuste.cpp", RAIZ / "platforms/switch/aviso.cpp"],
            grupos["lmnx_aurora_gx"][1]+["-DAURORA_ENABLE_GX=1", "-I" + str(plume), "-I" + str(RAIZ / "platforms/switch"), '-DLMNX_SHADER_BUILD_ID="' + identidad() + '"'], "c++20")
