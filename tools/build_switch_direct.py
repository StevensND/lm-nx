    manifiesto = json.loads((RAIZ / "platforms/switch/runtime_sources.json").read_text(encoding="utf-8"))
    _, banderas_core, estandar_core = grupos["lmnx_aot_runtime_core"]
    lista_core = manifiesto["compilables"]
    if args.runtime_completo or args.generados:
        lista_core += list(manifiesto["pendientes"])
    grupos["lmnx_aot_runtime_core"] = ([RAIZ / f for f in lista_core],
        banderas_core + ["-I" + str(RAIZ / "LMNX-Deko3D/third_party/xxhash"),
        "-I" + str(RAIZ / "extern/fuentes/imgui-1.91.9b-docking")], estandar_core)
    if args.generados_pal:
        grupos["lmnx_aot_runtime_core"][1].append("-DLM_SWITCH_PAL_MODULE=1")
    grupos["lmnx_imgui"] = ([RAIZ / "extern/fuentes/imgui-1.91.9b-docking" / f for f in
        ["imgui.cpp", "imgui_draw.cpp", "imgui_tables.cpp", "imgui_widgets.cpp"]],
        ["-I" + str(RAIZ / "extern/fuentes/imgui-1.91.9b-docking"), "-DIMGUI_DISABLE_DEFAULT_SHELL_FUNCTIONS=1"], "c++20")
    grupos["lmnx_xxhash"] = ([RAIZ / "LMNX-Deko3D/third_party/xxhash/xxhash.c"], [], "c++20")
    servicios = json.loads((RAIZ / "platforms/switch/aurora_sources.json").read_text(encoding="utf-8"))
    grupos["lmnx_aurora_servicios"] = ([aurora / f for f in servicios["servicios"]],
        ["-DAURORA=1", "-DTARGET_PC=1", "-DFMT_HEADER_ONLY=1"] + ["-I" + str(p) for p in
        [aurora / "include", aurora / "include/dolphin", aurora / "lib", RAIZ / "platforms/switch/nod", RAIZ / "platforms/switch/sdl3_headers/SDL3", *includes_locales()]], "c++20")
    grupos["lmnx_nod"] = ([RAIZ / "platforms/switch/nod/nod_gcn.cpp"],
        ["-I" + str(RAIZ / "platforms/switch/nod")], "c++20")
    if args.productor_nativo:
        from abseil_switch_sources import fuentes_abseil
        from prepare_abseil_switch import preparar as preparar_absl
        absl_overlay=preparar_absl()
        absl_raiz=fuente("abseil-cpp")
        absl_fuentes=[absl_overlay / f.relative_to(absl_raiz) if (absl_overlay / f.relative_to(absl_raiz)).is_file() else f for f in fuentes_abseil()]
        grupos["lmnx_abseil"] = (absl_fuentes, ["-I"+str(absl_overlay), "-I"+str(absl_raiz), "-I"+str(absl_raiz / "absl/time/internal/cctz/src"), "-DNDEBUG=1"], "c++20")
