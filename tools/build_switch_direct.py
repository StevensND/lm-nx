    optimizacion=preparar_optimizacion(args,salida,grupos)
    for grupo in GRUPOS & grupos.keys():grupos[grupo][1].extend(optimizacion["compilar"])
    if args.solo_grupo:
        desconocidos = set(args.solo_grupo) - grupos.keys()
        if desconocidos:
            raise SystemExit("Unknown groups: " + str(sorted(desconocidos)))
        grupos = {g: datos for g, datos in grupos.items() if g in args.solo_grupo}
