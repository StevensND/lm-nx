"""Builds tools/shader_forge.cpp: the shader caches for the console, made without the console.

    python tools/build_shader_forge.py                 PC build (tests), build/shader-forge/shader_forge.exe
    python tools/build_shader_forge.py --web           WebAssembly for the installer page (Emscripten),
                                                       build/shader-forge-web/shader_forge.{mjs,wasm}
    python tools/build_shader_forge.py <list> <out>    PC build, then run it (shader_forge arguments;
                                                       the list as data/pipelines.bin, compressed or not)

Sources: the Switch build's GX shader generator (Aurora prepared by tools/prepare_aurora_native.py), Tint
(the same targets as tools/build_tint_direct.py), the SwitchWaker translator and uam. The cache folder
name carries tools/shader_build_id.py, so the caches match the NRO built from the same sources.
"""
import argparse
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
from local_dependencies import RAIZ, includes_locales, fuente
from prepare_aurora_native import preparar_nativo
from prepare_tint_switch import preparar as preparar_tint
from shader_build_id import identidad
from uam_sources import fuentes as fuentes_uam, opciones as opciones_uam

MINGW = Path(str(Path(os.environ.get("DEVKITPRO", "/opt/devkitpro")) / "msys2/mingw64/bin"))
EMSDK = Path(os.environ.get("EMSDK", str(RAIZ / "extern/fuentes/emsdk")))
EXPORTS = ["forge_build_id", "forge_generate", "forge_compile", "forge_tint_data", "forge_tint_size",
           "forge_dksh_data", "forge_dksh_size", "forge_error", "malloc", "free"]


def builtin_include(out):
    """shader_forge_builtin.inc from tools/shader_forge_builtin.json (raw string literals)."""
    data = json.loads((RAIZ / "tools/shader_forge_builtin.json").read_text(encoding="utf-8"))
    lines = ["// Generated by tools/build_shader_forge.py from tools/shader_forge_builtin.json.",
             "const Builtin kBuiltins[] = {"]
    for s in data["shaders"]:
        assert ')lmnx"' not in s["wgsl"]
        lines.append(f'  {{R"lmnx({s["wgsl"]})lmnx", "{s["entry"]}", {int(s["stage"])}u}},')
    lines.append("};")
    path = out / "shader_forge_builtin.inc"
    text = "\n".join(lines) + "\n"
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def tint_sources():
    """The Tint sources tools/build_tint_direct.py compiles (WGSL reader, inspector, GLSL writer)."""
    tint = fuente("dawn")
    overlay = preparar_tint()
    manifest = RAIZ / "build/shader-forge-tint.tsv"
    subprocess.run([str(Path(os.environ.get("CMAKE", "cmake"))), "-DTINT_ROOT=" + tint.as_posix(),
                    "-DSALIDA=" + manifest.as_posix(), "-DTINT_BUILD_IS_WIN=OFF", "-P", str(RAIZ / "tools/tint_manifest.cmake")],
                   cwd=tint / "src/tint", check=True, capture_output=True)
    sources, deps, external = (defaultdict(list) for _ in range(3))
    for line in manifest.read_text(encoding="utf-8").splitlines():
        k, name, items = line.split("|")
        {"S": sources, "D": deps, "E": external}[k][name] += [s for s in items.split(";") if s]
    seen = set()

    def walk(name):
        if name not in seen:
            seen.add(name)
            for d in deps[name]:
                walk(d)

    for name in ("tint_api", "tint_lang_wgsl_reader", "tint_lang_wgsl_inspector", "tint_lang_glsl_writer"):
        walk(name)
    files = sorted({tint / "src/tint" / s for n in seen for s in sources[n] if s.endswith(".cc")})
    files = [overlay / s.relative_to(tint) if (overlay / s.relative_to(tint)).is_file() else s for s in files]
    files += [tint / "src/utils" / n for n in ("assert.cc", "log.cc", "placeholder.cc")]
    absl = fuente("abseil-cpp")
    files += [absl / n for n in ("absl/strings/charconv.cc", "absl/strings/internal/charconv_bigint.cc",
              "absl/strings/internal/charconv_parse.cc", "absl/base/internal/raw_logging.cc", "absl/base/log_severity.cc",
              "absl/numeric/int128.cc", "absl/strings/internal/memutil.cc", "absl/strings/ascii.cc")]
    flags = ["-DNDEBUG", "-I" + str(overlay), "-I" + str(tint), "-I" + str(tint / "include"), "-I" + str(absl)]
    on = {"GLSL_WRITER", "WGSL_READER", "WGSL_WRITER"}
    for n in ["GLSL_VALIDATOR", "GLSL_WRITER", "HLSL_WRITER", "IR_BINARY", "IS_LINUX", "IS_MAC", "IS_WIN",
              "MSL_WRITER", "SPV_READER", "SPV_WRITER", "WGSL_READER", "WGSL_WRITER", "NULL_WRITER", "TINTD"]:
        flags.append(f"-DTINT_BUILD_{n}={int(n in on)}")
    flags += ["-DTINT_ENABLE_IR_DUMPING=0", "-DTINT_ENABLE_IR_VALIDATION_ASSERTS=0", "-DTINT_ENABLE_BREAK_IN_DEBUGGER=0"]
    return files, flags


def plan(out, web):
    """(source, language, flags) for every unit."""
    aurora = preparar_nativo()
    translator = RAIZ / "LMNX-Deko3D/third_party/switchwaker_translate"
    uam = RAIZ / "LMNX-Deko3D/third_party/uam"
    deko = RAIZ / "LMNX-Deko3D/include"
    gx_includes = [aurora / "include", aurora / "include/dolphin", aurora / "lib", deko, RAIZ / "LMNX-Deko3D/third_party/xxhash",
                   RAIZ / "platforms/switch/sdl3_headers/SDL3", *includes_locales()]
    gx_flags = ["-DAURORA=1", "-DTARGET_PC=1", "-DFMT_HEADER_ONLY=1", "-DXXH_INLINE_ALL=1", *["-I" + str(p) for p in gx_includes]]
    units = [(aurora / "lib" / f, "c++", gx_flags) for f in ("gx/shader.cpp", "gx/shader_info.cpp", "gx/gx.cpp", "gx/attr_fmt.cpp", "logging.cpp")]
    units.append((fuente("abseil-cpp") / "absl/container/internal/raw_hash_set.cc", "c++", gx_flags))
    tint_files, tint_flags = tint_sources()
    units += [(f, "c++", tint_flags) for f in tint_files]
    units.append((translator / "shader_translate.cpp", "c++", tint_flags + ["-I" + str(translator), "-I" + str(deko)]))
    # Windows has no posix_memalign; Emscripten does.
    uam_flags = [f for f in opciones_uam(uam) if web or f != "-DHAVE_POSIX_MEMALIGN"] + ["-DHAVE_STRNDUP=1", "-I" + str(deko)]
    if web:
        uam_flags.append("-DPIPE_ARCH_LITTLE_ENDIAN")  # Mesa only knows the CPU families; WebAssembly is little-endian
    # Mesa's c99_math.h defines signbit as a macro when it is not one, as in libc++ (Emscripten), where the
    # macro then breaks <compare> inside <algorithm>: those headers are read first.
    uam_cxx = uam_flags + (["-include", "cmath", "-include", "algorithm"] if web else [])
    units += [(f, "c", uam_flags) if f.suffix == ".c" else (f, "c++", uam_cxx) for f in fuentes_uam(uam)]
    # zstd's decoder, for the list as data/pipelines.bin ships it.
    zstd = fuente("zstd") / "lib"
    zstd_flags = ["-DZSTD_DISABLE_ASM", "-DZSTD_MULTITHREAD=0", "-I" + str(zstd), "-I" + str(zstd / "common")]
    units += [(zstd / f, "c", zstd_flags) for f in ("common/debug.c", "common/entropy_common.c", "common/error_private.c",
              "common/fse_decompress.c", "common/xxhash.c", "common/zstd_common.c", "decompress/huf_decompress.c",
              "decompress/zstd_ddict.c", "decompress/zstd_decompress.c", "decompress/zstd_decompress_block.c")]
    forge_flags = gx_flags + tint_flags + ["-I" + str(translator), "-I" + str(uam), "-I" + str(out), "-I" + str(zstd),
                                           f'-DLMNX_SHADER_BUILD_ID="{identidad()}"']
    units.append((RAIZ / "tools/shader_forge.cpp", "c++", forge_flags))
    return units


def toolchain(web):
    env = os.environ.copy()
    if not web:
        env["PATH"] = str(MINGW) + os.pathsep + env["PATH"]
        return env, MINGW / "gcc.exe", MINGW / "g++.exe"
    node = next((EMSDK / "node").glob("*"))
    python = next((EMSDK / "python").glob("*"))
    env.update(EMSDK=str(EMSDK), EM_CONFIG=str(EMSDK / ".emscripten"), EMSDK_NODE=str(node / "node.exe"),
               EMSDK_PYTHON=str(python / "python.exe"))
    env["PATH"] = os.pathsep.join([str(EMSDK / "upstream/emscripten"), str(node), str(python), env["PATH"]])
    em = EMSDK / "upstream/emscripten"
    return env, em / "emcc.exe", em / "em++.exe"


def build(web=False, jobs=8):
    out = RAIZ / "build" / ("shader-forge-web" if web else "shader-forge")
    (out / "obj").mkdir(parents=True, exist_ok=True)
    builtin_include(out)
    env, cc, cxx = toolchain(web)
    env["TMP"] = env["TEMP"] = str(out)
    common = ["-O2", "-ffunction-sections", "-fdata-sections"]
    header_time = max(p.stat().st_mtime for p in (RAIZ / "LMNX-Deko3D").rglob("*") if p.is_file() and p.suffix in (".h", ".hpp"))

    def compile_unit(unit):
        src, lang, flags = unit
        obj = out / "obj" / (src.stem + "-" + hashlib.sha256(str(src).encode()).hexdigest()[:12] + ".o")
        # LTO only for the GX generator: it drops the Aurora code the generator does not reach (and its
        # references to the renderer). Mesa (uam) breaks under LTO.
        lto = ["-flto"] if not web and ("-DAURORA=1" in flags) else []
        cmd = [str(cc if lang == "c" else cxx), *common, *lto, "-std=gnu99" if lang == "c" else "-std=c++20", *flags, "-c", str(src), "-o", str(obj)]
        extra = (out / "shader_forge_builtin.inc").read_bytes() if src.name == "shader_forge.cpp" else b""
        digest = hashlib.sha256((json.dumps(cmd) + hashlib.sha256(src.read_bytes() + extra).hexdigest()).encode()).hexdigest()
        stamp = obj.with_suffix(".sha256")
        if obj.exists() and stamp.exists() and stamp.read_text() == digest and obj.stat().st_mtime >= header_time:
            return obj, None
        r = subprocess.run(cmd, cwd=RAIZ, env=env, capture_output=True)
        if r.returncode:
            return obj, (src, (r.stdout + r.stderr).decode(errors="replace"))
        stamp.write_text(digest)
        return obj, None

    units = plan(out, web)
    print(f"shader forge ({'web' if web else 'pc'}): {len(units)} units", flush=True)
    objects, failures = [], []
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        for i, (obj, failure) in enumerate(pool.map(compile_unit, units), 1):
            objects.append(obj)
            if failure:
                failures.append(failure)
            if i % 100 == 0:
                print(f"{i}/{len(units)}", flush=True)
    if failures:
        src, log = failures[0]
        sys.exit(f"{len(failures)} units failed; first: {src}\n{log[:4000]}")
    rsp = out / "link.rsp"
    rsp.write_text("\n".join('"' + str(o).replace("\\", "/") + '"' for o in objects), encoding="utf-8")
    if web:
        target = out / "shader_forge.mjs"
        cmd = [str(cxx), "-O2", "@" + str(rsp), "-o", str(target), "-sMODULARIZE=1", "-sEXPORT_ES6=1",
               "-sENVIRONMENT=web,worker,node", "-sALLOW_MEMORY_GROWTH=1", "-sINITIAL_MEMORY=64MB", "-sSTACK_SIZE=4MB",
               "-sEXPORTED_FUNCTIONS=" + ",".join("_" + e for e in EXPORTS),
               "-sEXPORTED_RUNTIME_METHODS=HEAPU8,UTF8ToString", "-Wl,--gc-sections"]
    else:
        target = out / "shader_forge.exe"
        cmd = [str(cxx), "-O2", "-flto", "-static", "-Wl,--gc-sections", "@" + str(rsp), "-o", str(target),
               "-lpsapi", "-ldbghelp", "-lws2_32"]
    r = subprocess.run(cmd, cwd=RAIZ, env=env, capture_output=True)
    (out / "link.log").write_bytes(r.stdout + r.stderr)
    if r.returncode:
        sys.exit("link failed:\n" + (r.stdout + r.stderr).decode(errors="replace")[-6000:])
    print(f"built {target}", flush=True)
    return target, env


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--web", action="store_true")
    p.add_argument("--jobs", type=int, default=8)
    a, run = p.parse_known_args()
    exe, env = build(a.web, a.jobs)
    if run and not a.web:
        sys.exit(subprocess.run([str(exe), *run], env=env).returncode)
